"""Builds QF1_Complete.cir from the two board netlists (keeps one source of truth)."""
import re
main = open('QF1_Main_Filter.cir').read()
amp = open('QF1_Amp_Supply.cir').read()
def body(s, start, end):
    return s[s.index(start):s.index(end)]
m = body(main, '.param FREQ', '* ---- analysis')
m = m.replace('VB BPIN 0 {VSUP}\n', '* main board pin 1 fed from the amp board B+ (node BPA)\n')
m = m.replace('D1 BPIN BPLUS', 'D1 BPA BPLUS')
m = re.sub(r'\* load = amp board input.*\nRLOAD OUT_QF1 BIAS 112k\n', '', m)
a = body(amp, '* ---- AC input', '* ---- analysis')
a = re.sub(r'\bBPLUS\b', 'BPA', a)
a = re.sub(r'\* ---- test signal.*?\n\n', '', a, flags=re.S)
a = re.sub(r'\bIN\b', 'OUT_QF1', a)
head = """* Autek QF-1 -- COMPLETE UNIT: main filter board + audio power amp / AC supply board
* Generated by make_complete.py from QF1_Main_Filter.cir and QF1_Amp_Supply.cir.
* Receiver audio -> filter -> amp -> speaker; the amp board's bridge supply powers everything.
* In LTspice: File > Open (Netlists), Run. Probe V(audio_out) (speaker), V(out_qf1), V(bpa).
* Controls: FREQ, SEL, MODE, LOGPOT (see QF1_Main_Filter.cir). FREQ=0.024 puts the peak near 1 kHz.

.include qf1_models.lib
.param VACRMS=12 RLOAD=8 MAINS=50
"""
tail = """
* ---- analysis (LTspice). Supply settles in ~0.3 s.
.tran 10u 0.6 0.5 10u
.param FREQ=0.024 SEL=0.8 MODE=1 FSIG=1k VAMP=0.05
*.step param FSIG list 900 950 1000 1050 1100
.meas TRAN vout MAX V(audio_out)
.end
"""
m = m.replace('.param FREQ=0.5 SEL=0.7 MODE=1 LOGPOT=0', '.param LOGPOT=0')
m = m.replace('.param VSUP=15 VAMP=0.5 FSIG=1k\n', '')
open('QF1_Complete.cir', 'w').write(head + m + '\n' + a + tail)
print("wrote QF1_Complete.cir")
