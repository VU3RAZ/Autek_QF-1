"""QF filter main board schematic + physical layout."""
from sch import S, FONTB, FONT

BX1, BY1, BX2, BY2 = 30, 30, 1040, 520


def draw_main(c, ox, oy, s, d=None):
    d = d or S(c, ox, oy, s)
    T = d.text
    d.rect(BX1, BY1, BX2, BY2, w=1.0, dash=(7, 4))

    def term(x, y, lab, where):
        d.term(x, y, lab)
        if where == "b":
            T(x, y + 15, lab, 8.5, "c", FONTB)
        elif where == "t":
            T(x, y - 7, lab, 8.5, "c", FONTB)
        elif where == "l":
            T(x - 7, y + 3.5, lab, 8.5, "r", FONTB)
        else:
            T(x + 7, y + 3.5, lab, 8.5, "l", FONTB)

    GL = 185   # ground line
    BP = 48    # B+ line

    # ---------------- supply, bias, ground
    term(110, BY1, "1", "t")
    T(110, 12, "(B+)", 7, "c")
    d.wire((110, BY1), (110, BP))
    d.diode((110, BP), (180, BP))
    T(145, 64, "D1\n(1N4001)", 7.5, "c")
    d.dot(190, BP)
    d.wire((180, BP), (190, BP))
    d.wire((190, BP), (190, 70))
    d.arrow((190, 70), (226, 70), size=6)
    T(232, 67, "B+", 7.5, "l", FONTB)
    T(232, 77, "TO PINS 9 & 13 OF U1, U2 & U3", 7.5, "l")

    u4 = d.opamp(820, 125, "U4", pins=dict(inv=2, non=3, out=6, top=7, bot=4))
    p7x, p7y = u4["top"]
    p4x, p4y = u4["bot"]
    d.wire((190, BP), (p7x, BP))
    d.wire((p7x, p7y), (p7x, BP), hops=[(p7x, 94), (p7x, 68)])

    # R21 / R20 divider, C12
    d.dot(640, BP)
    d.res((640, BP), (640, 122))
    T(632, 92, "R21\n220K", 7.5, "r")
    d.dot(640, 122)
    T(646, 118, "B+/2", 7, "l")
    d.res((640, 122), (640, GL))
    T(632, 155, "R20\n220K", 7.5, "r")
    d.wire((640, 122), (690, 122))
    d.dot(690, 122)
    d.cap((690, 122), (690, GL), polar="p1")
    T(700, 158, "C12\n22µF", 7.5, "l")
    d.wire((690, 122), (690, 100))
    d.arrow((690, 100), (718, 100), size=6)
    d.circA(727, 100)
    T(737, 103, "TO U1, U2, U3", 7, "l")
    # U4 + input from B+/2
    d.wire((690, 122), (770, 122), (770, u4["non"][1]), u4["non"])

    # ground: pins 20 & 7
    term(BX1, 175, "20", "l")
    term(BX1, 197, "7", "l")
    T(BX1 - 26, 189, "(GNDS)", 7, "r")
    d.wire((BX1, 175), (60, 175), (60, GL))
    d.wire((BX1, 197), (60, 197), (60, GL))
    d.dot(60, GL)
    d.wire((60, GL), (p4x, GL), hops=[(800, GL)][0:0])
    for x in (640, 690, p4x):
        d.dot(x, GL)
    d.dot(125, GL)
    d.chassis(125, GL, lead=8)
    d.dot(85, GL)
    d.wire((85, GL), (85, 214))
    d.arrow((85, 214), (112, 214), size=6)
    T(118, 211, "GND", 7.5, "l", FONTB)
    T(118, 221, "TO PIN 4  U1, U2 & U3", 7.5, "l")
    d.wire((p4x, p4y), (p4x, GL))

    # U4 feedback, C11 input
    X = 800
    xin = u4["inv"][1]
    d.wire((X, xin), u4["inv"])
    d.dot(X, xin)
    d.dot(X, 94)
    d.wire((X, 68), (X, 232), hops=[(X, u4["non"][1]), (X, GL)])
    d.wire((X, 94), (852, 94))
    d.res((852, 94), (895, 94), body=26)
    T(873, 86, "R25 100K", 6.5, "c")
    d.wire((X, 68), (852, 68))
    d.cap((852, 68), (895, 68))
    T(905, 66, "C6\n1000pF", 7.5, "l")
    d.wire((895, 68), (895, 125))
    d.dot(895, 94)
    d.wire(u4["out"], (895, 125))
    d.dot(895, 125)
    d.res((895, 125), (960, 125))
    T(927, 104, "R26\n100Ω", 7.5, "c")
    T(927, 113 - 9, "", 7.5, "c")
    d.dot(960, 125)
    d.wire((960, 125), (960, BY1))
    term(960, BY1, "21", "t")
    T(960, 12, "(QF-1 OUTPUT)", 7, "c")
    d.cap((960, 125), (1040, 125), polar="p1")
    T(1000, 146, "C7\n22µF", 7.5, "c")
    term(BX2, 125, "2", "r")
    T(1048, 142, "(OUTPUT\nEXCEPT\nQF-1)", 6.5, "l")
    d.arrow((1060, 64), (1006, 115), size=6)
    T(1062, 58, "(NOT\nINCLUDED\nIN QF-1)", 6.5, "l")
    # C11 to switch-2 common (pin 3)
    d.cap((X, 232), (900, 232))
    T(850, 222, "C11  .22µF", 7.5, "c")
    d.wire((900, 232), (1020, 232), (1020, BY2))

    # ---------------- section 1: U1A, U1B, U2A
    term(BX1, 260, "4", "l")
    T(BX1 - 18, 263, "(INPUT)", 7, "r")
    d.wire((BX1, 260), (90, 260))
    d.cap((90, 260), (90, 305))
    T(80, 276, "C1\n.01µF\n1 KV", 7.5, "r")
    d.res((90, 305), (90, 380))
    T(80, 340, "R1\n100K", 7.5, "r")
    d.wire((90, 380), (150, 380))
    d.dot(130, 380)

    u1a = d.opamp(150, 392, "U1A", pins=dict(inv=1, non=2, out=12))
    d.wire(u1a["non"], (140, 404), (140, BY2))
    term(140, BY2, "5", "b")
    # R2 and R17 line from summing node
    d.wire((130, 380), (130, 300))
    d.dot(130, 335)
    d.res((130, 335), (225, 335))
    T(178, 325, "R2  22K", 7.5, "c")
    d.wire(u1a["out"], (225, 392))
    d.dot(225, 392)
    d.wire((225, 392), (225, 270), hops=[(225, 300)])
    d.dot(225, 335)
    # R16 / R15 summer (notch 1)
    d.res((225, 270), (350, 270))
    T(288, 260, "R16  3.3K", 7.5, "c")
    d.dot(350, 270)
    d.res((350, 270), (480, 270))
    T(415, 260, "R15  3.3K", 7.5, "c")
    d.wire((350, 270), (350, 250), (500, 250), (500, BY2))
    term(500, BY2, "10", "b")
    # R17 || C9
    d.wire((130, 300), (380, 300))
    d.res((380, 300), (450, 300))
    d.wire((450, 300), (480, 300))
    d.dot(380, 300)
    d.dot(450, 300)
    d.wire((380, 300), (380, 340))
    d.cap((380, 340), (450, 340))
    d.wire((450, 340), (450, 300))
    T(415, 293, "R17  22K", 7.5, "c")
    T(415, 358, "C9", 7.5, "c")

    # U1B integrator
    d.res((225, 392), (285, 392))
    T(255, 384, "R3", 7.5, "c")
    u1b = d.opamp(295, 404, "U1B", pins=dict(inv=7, non=6, out=10))
    d.wire((285, 392), u1b["inv"])
    d.dot(285, 392)
    d.wire((285, 392), (285, 360))
    d.cap((285, 360), (365, 360))
    T(325, 350, "C2  .018µF", 7.5, "c")
    d.wire((365, 360), (365, 404))
    d.wire(u1b["out"], (365, 404))
    d.dot(365, 404)
    d.wire((365, 404), (365, BY2))
    term(365, BY2, "8", "b")
    d.wire(u1b["non"], (278, 416))
    d.dot(278, 416)
    d.wire((278, 416), (278, 452))
    d.arrow((278, 452), (300, 452), size=5)
    d.circA(306, 452)
    T(306, 472, "(B+/2)", 7, "c")
    d.wire((278, 416), (258, 416))
    d.res((258, 416), (258, BY2))
    T(250, 470, "R4", 7.5, "r")
    term(258, BY2, "6", "b")

    # U2A integrator
    u2a = d.opamp(410, 404, "U2A", pins=dict(inv=1, non=2, out=12))
    d.wire((392, 392), u2a["inv"])
    d.dot(392, 392)
    d.wire((392, 392), (392, 360))
    d.cap((392, 360), (480, 360))
    T(436, 350, "C3  .018µF", 7.5, "c")
    d.res((392, 392), (392, BY2))
    T(386, 468, "R5", 7.5, "r")
    term(392, BY2, "9", "b")
    d.wire(u2a["non"], (402, 416), (402, 448))
    d.arrow((402, 448), (424, 448), size=5)
    d.circA(430, 448)
    T(432, 468, "(B+/2)", 7, "c")
    d.wire(u2a["out"], (480, 404))
    d.wire((480, 270), (480, BY2))
    for y in (300, 360, 404):
        d.dot(480, y)
    term(480, BY2, "11", "b")

    # ---------------- section 2: U2B, U3A, U3B
    d.res((535, BY2), (535, 392))
    T(527, 470, "R6\n22K", 7.5, "r")
    term(535, BY2, "12", "b")
    d.dot(535, 392)
    u2b = d.opamp(560, 404, "U2B", pins=dict(inv=7, non=6, out=10))
    d.wire((535, 392), u2b["inv"])
    d.wire(u2b["non"], (550, 416), (550, BY2))
    term(550, BY2, "13", "b")
    d.wire((535, 392), (535, 300))
    d.dot(535, 335)
    d.res((535, 335), (640, 335))
    T(588, 325, "R7  22K", 7.5, "c")
    d.wire(u2b["out"], (640, 404))
    d.wire((640, 404), (640, 270), hops=[(640, 300)])
    d.dot(640, 335)
    d.dot(640, 392)
    # R13 / R12 summer (notch 2)
    d.res((640, 270), (800, 270))
    T(720, 260, "R13  3.3K", 7.5, "c")
    d.dot(800, 270)
    d.res((800, 270), (950, 270))
    T(875, 260, "R12  3.3K", 7.5, "c")
    d.wire((800, 270), (800, 250), (990, 250), (990, BY2))
    term(990, BY2, "17", "b")
    # R14 || C10
    d.wire((535, 300), (840, 300))
    d.res((840, 300), (910, 300))
    d.wire((910, 300), (950, 300))
    d.dot(840, 300)
    d.dot(910, 300)
    d.wire((840, 300), (840, 340))
    d.cap((840, 340), (910, 340))
    d.wire((910, 340), (910, 300))
    T(875, 293, "R14  22K", 7.5, "c")
    T(875, 358, "C10", 7.5, "c")

    # R8 trim pot -> U3A
    d.trimpot((640, 392), (708, 392))
    T(668, 374, "R8 10K\nTRIM-POT", 6.5, "c")
    u3a = d.opamp(725, 404, "U3A", pins=dict(inv=1, non=2, out=12))
    d.wire((708, 392), u3a["inv"])
    d.dot(712, 392)
    d.wire((712, 392), (712, 360))
    d.cap((712, 360), (795, 360))
    T(754, 350, "C4  .018µF", 7.5, "c")
    d.wire((795, 360), (795, 404))
    d.wire(u3a["out"], (795, 404))
    d.dot(795, 404)
    d.wire((795, 404), (795, BY2))
    term(795, BY2, "18", "b")
    d.dot(795, 436)
    d.wire((795, 436), (825, 436))
    d.res((825, 436), (825, BY2))
    T(833, 476, "R24\n10K", 7.5, "l")
    term(825, BY2, "19", "b")
    d.wire(u3a["non"], (717, 416))
    d.dot(717, 416)
    d.wire((717, 416), (717, 450))
    d.arrow((717, 450), (738, 450), size=5)
    d.circA(744, 450)
    T(752, 470, "(B+/2)", 7, "c")
    d.wire((717, 416), (700, 416))
    d.res((700, 416), (700, BY2))
    T(693, 476, "R9", 7.5, "r")
    term(700, BY2, "16", "b")

    # U3B integrator
    u3b = d.opamp(875, 404, "U3B", pins=dict(inv=7, non=6, out=10))
    d.wire((860, 392), u3b["inv"])
    d.dot(860, 392)
    d.wire((860, 392), (860, 360))
    d.cap((860, 360), (950, 360))
    T(905, 350, "C5  .018µF", 7.5, "c")
    d.res((860, 392), (860, BY2))
    T(866, 476, "R10", 7.5, "l")
    term(860, BY2, "15", "b")
    d.wire(u3b["non"], (868, 416), (868, 448))
    d.arrow((868, 448), (888, 448), size=5)
    d.circA(894, 448)
    T(900, 468, "(B+/2)", 7, "c")
    d.wire(u3b["out"], (950, 404))
    d.wire((950, 270), (950, 404))
    for y in (300, 360, 404):
        d.dot(950, y)
    d.res((950, 404), (950, BY2))
    T(958, 470, "R11", 7.5, "l")
    term(950, BY2, "14", "b")
    term(1020, BY2, "3", "b")


def draw_main_layout(c, ox, oy, s):
    """Physical layout of the main board (circles = I/O connection points)."""
    d = S(c, ox, oy, s, lw=1.0)
    T = d.text
    d.rect(0, 20, 300, 170, w=1.3)
    d.ocircle(140, 26, 2.4)
    d.line((140, 23), (140, 12))
    T(140, 2, "GND\n20", 7, "c")
    d.ocircle(48, 70, 2.4)
    d.arrow((-38, 74), (42, 70), size=4, w=0.8)
    T(-40, 76, "21\nQF1-OUT", 6.5, "r")

    def ic(x, y, name, top, bot, dot_tr=False):
        d.rect(x, y, x + 64, y + 30)
        T(x + 32, y + 20, name, 10, "c", FONTB)
        d.ocircle(x + (57 if dot_tr else 7), y + (7 if dot_tr else 23), 2.2)
        d.arrow((x + 56, y - 5), (x + 10, y - 5), size=4, w=0.7)
        T(x + 6, y - 2.5, top[0], 6.5, "r")
        T(x + 60, y - 2.5, top[1], 6.5, "l")
        d.arrow((x + 10, y + 38), (x + 56, y + 38), size=4, w=0.7)
        T(x + 6, y + 40.5, bot[0], 6.5, "r")
        T(x + 60, y + 40.5, bot[1], 6.5, "l")

    ic(60, 45, "U4", ("4", "1"), ("5", "8"), dot_tr=True)
    ic(180, 45, "U3", ("14", "8"), ("1", "7"))
    ic(60, 98, "U1", ("14", "8"), ("1", "7"))
    ic(180, 98, "U2", ("14", "8"), ("1", "7"))
    d.arrow((30, 97), (64, 119), size=4, w=0.7)
    T(28, 97, "DOT", 6.5, "r")
    T(42, 142, "PIN", 6.5, "r")
    # connection rows
    xs1 = [20 + i * 12 for i in range(7)]
    for x in xs1:
        d.ocircle(x, 160, 2.6)
    xs2 = [155 + i * 12 for i in range(12)]
    for i, x in enumerate(xs2):
        d.ocircle(x, 160 if i >= 4 else 150, 2.6)
    for i, x in enumerate(xs1):
        T(x, 184, str(i + 1), 6.5, "c")
    for i, x in enumerate(xs2):
        T(x, 184, str(i + 8), 6, "c")
    for x, lab in ((20, "B+"), (32, "OUT"), (56, "IN"), (92, "GND")):
        d.line((x, 188), (x, 196))
        T(x, 206, lab, 6.5, "c")
    T(320, 40, "PHYSICAL\nLAYOUT.\n(CIRCLES =\nINPUT/OUTPUT\nCONNECTION\nLOCATION)", 7.5, "l")
